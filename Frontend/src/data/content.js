/** Pick FR/EN field: pickLang(item, 'desc', lang) */
export function pickLang(item, field, lang = 'FR') {
  if (!item) return '';
  if (lang === 'EN' && item[field + 'En']) return item[field + 'En'];
  return item[field] || '';
}
