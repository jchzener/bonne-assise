export function getUpcomingEvents({ now = new Date(), category, includeDrafts = false }: { now?: Date; category?: EventCategory; includeDrafts?: boolean } = {}) {
  return events.filter((event) => {
    const active = new Date(event.endsAt).getTime() >= now.getTime();
    return active && (includeDrafts || event.status === "verified") && (!category || event.category === category);
  }).sort((a, b) => Number(b.sponsored) - Number(a.sponsored) || (a.featuredRank ?? 999) - (b.featuredRank ?? 999) || a.startsAt.localeCompare(b.startsAt));
}
